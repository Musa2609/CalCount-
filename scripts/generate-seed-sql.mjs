/**
 * Generates supabase/seed/0004_seed_foods.sql from src/data/foodSeed.json.
 * Run: node scripts/generate-seed-sql.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const seed = JSON.parse(readFileSync(join(root, 'src/data/foodSeed.json'), 'utf8'));

const q = (value) => {
  if (value === null || value === undefined) return 'null';
  return `'${String(value).replace(/'/g, "''")}'`;
};

const num = (value) => {
  if (value === null || value === undefined) return 'null';
  return String(value);
};

const servingId = (foodId, serial) =>
  `${foodId.slice(0, 24)}${String(serial).padStart(12, '0')}`;

const foodRows = [];
const servingRows = [];

for (const food of seed.foods) {
  foodRows.push(
    `  (${q(food.id)}, null, ${q(food.name)}, ${q(food.brand)}, ${q(food.category)}, ${q(
      food.description,
    )}, ${q(food.servingName)}, ${num(food.servingGrams)}, ${num(food.kcal)}, ${num(
      food.protein,
    )}, ${num(food.carbs)}, ${num(food.fat)}, ${num(food.fiber)}, ${num(food.sugar)}, ${num(
      food.sodium,
    )}, ${q(food.source)}, ${q(food.sourceUrl)}, ${q(food.quality)}, ${q(food.cuisine)}, ${q(
      food.barcode,
    )}, null, true)`,
  );

  const definitions = [
    { label: food.servingName, grams: food.servingGrams, isDefault: true },
    ...(food.extraServings ?? []).map((serving) => ({ ...serving, isDefault: false })),
    { label: '100 g', grams: 100, isDefault: false },
  ].filter(
    (serving, index, all) =>
      all.findIndex((candidate) => candidate.grams === serving.grams) === index,
  );

  definitions.forEach((serving, index) => {
    servingRows.push(
      `  (${q(servingId(food.id, index + 1))}, ${q(food.id)}, ${q(serving.label)}, ${num(
        serving.grams,
      )}, ${serving.isDefault ? 'true' : 'false'}, ${index + 1})`,
    );
  });
}

const sql = `-- Auto-generated by scripts/generate-seed-sql.mjs — do not edit by hand.
-- Shared food catalogue. All rows are public read-only reference data.
-- Values are per 100 g; see source/source_url/data_quality on every row.

insert into public.foods (
  id, user_id, name, brand, category, description, serving_name, serving_grams,
  calories_per_100g, protein_per_100g, carbs_per_100g, fat_per_100g,
  fiber_per_100g, sugar_per_100g, sodium_per_100g,
  source, source_url, data_quality, cuisine, barcode, image_url, is_public
) values
${foodRows.join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  brand = excluded.brand,
  category = excluded.category,
  description = excluded.description,
  serving_name = excluded.serving_name,
  serving_grams = excluded.serving_grams,
  calories_per_100g = excluded.calories_per_100g,
  protein_per_100g = excluded.protein_per_100g,
  carbs_per_100g = excluded.carbs_per_100g,
  fat_per_100g = excluded.fat_per_100g,
  fiber_per_100g = excluded.fiber_per_100g,
  sugar_per_100g = excluded.sugar_per_100g,
  sodium_per_100g = excluded.sodium_per_100g,
  source = excluded.source,
  source_url = excluded.source_url,
  data_quality = excluded.data_quality,
  cuisine = excluded.cuisine,
  barcode = excluded.barcode,
  is_public = excluded.is_public;

insert into public.food_servings (id, food_id, label, grams, is_default, sort_order) values
${servingRows.join(',\n')}
on conflict (id) do update set
  label = excluded.label,
  grams = excluded.grams,
  is_default = excluded.is_default,
  sort_order = excluded.sort_order;
`;

mkdirSync(join(root, 'supabase/seed'), { recursive: true });
writeFileSync(join(root, 'supabase/seed/0004_seed_foods.sql'), sql, 'utf8');
console.log(
  `Wrote ${foodRows.length} foods and ${servingRows.length} servings to supabase/seed/0004_seed_foods.sql`,
);
